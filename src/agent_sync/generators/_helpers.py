"""Shared helpers for framework generators."""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

TOOL_NAME = "agent-sync"


@dataclass
class SyncContext:
    repo_root: Path
    source_prefix: str
    project_name: str

    def header(self, source: str) -> str:
        return (
            f"<!-- AUTO-GENERATED by {TOOL_NAME} — DO NOT EDIT. "
            f"Source: {self.source_prefix}/{source} -->\n"
        )


def globs_to_apply_to(globs: str) -> str:
    parts = [g.strip() for g in globs.split(",")]
    if len(parts) == 1:
        return f"'{parts[0]}'"
    return ", ".join(f"'{p}'" for p in parts)


def globs_to_list(globs: str) -> str:
    parts = [g.strip() for g in globs.split(",")]
    return "[" + ", ".join(f"'{p}'" for p in parts) + "]"


def globs_to_paths(globs: str) -> str:
    parts = [g.strip() for g in globs.split(",")]
    lines = ["paths:"]
    for p in parts:
        lines.append(f"  - '{p}'")
    return "\n".join(lines)


def frontmatter_description(description: str) -> str:
    return f"description: {json.dumps(description)}"
