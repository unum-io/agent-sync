"""Golden-style generator tests."""

from pathlib import Path

import pytest

from agent_sync.config import load_config
from agent_sync.generators.claude import generate_claude
from agent_sync.generators.copilot import generate_copilot, generate_copilot_skill
from agent_sync.generators.cursor import generate_cursor, generate_cursor_command
from agent_sync.generators._helpers import SyncContext
from agent_sync.sync import sync

FIXTURES = Path(__file__).parent / "fixtures" / "minimal"


@pytest.fixture
def ctx(tmp_path: Path) -> SyncContext:
    return SyncContext(
        repo_root=tmp_path,
        source_prefix=".ai",
        project_name="TestProject",
    )


def test_claude_general_uses_project_name(ctx: SyncContext):
    item = {"name": "general", "file": "instructions/general.md"}
    paths = generate_claude(item, "body content", ctx)
    assert paths[0][0].name == "CLAUDE.md"
    content = paths[0][1]
    assert content.startswith("# TestProject\n\n")
    assert "AUTO-GENERATED by agent-sync" in content
    assert "body content" in content


def test_cursor_rule_frontmatter(ctx: SyncContext):
    item = {
        "name": "python",
        "file": "instructions/python.md",
        "description": "Python standards",
        "globs": "**/*.py",
    }
    paths = generate_cursor(item, "python rules", ctx)
    content = paths[0][1]
    assert "alwaysApply" not in content
    assert "globs: ['**/*.py']" in content
    assert "python rules" in content


def test_copilot_command_skill(ctx: SyncContext):
    item = {
        "name": "review",
        "file": "commands/review.md",
        "description": "Code review",
    }
    paths = generate_copilot_skill(item, "review steps", ctx)
    assert paths[0][0].as_posix().endswith(".github/skills/review/SKILL.md")
    assert 'name: "review"' in paths[0][1]


def test_cursor_command(ctx: SyncContext):
    item = {"name": "review", "file": "commands/review.md"}
    paths = generate_cursor_command(item, "review body", ctx)
    assert paths[0][0].name == "review.md"


def test_full_sync_generates_expected_files(tmp_path: Path):
    fixture_ai = FIXTURES / ".ai"
    repo = tmp_path / "repo"
    repo.mkdir()
    _copy_tree(fixture_ai, repo / ".ai")

    written = sync(repo, dry_run=False)
    paths = {p.relative_to(repo).as_posix() for p in written}

    assert "CLAUDE.md" in paths
    assert "AGENTS.md" in paths
    assert ".cursor/rules/general-instructions.mdc" in paths
    assert ".cursor/rules/python.mdc" in paths
    assert ".cursor/commands/review.md" in paths
    assert ".github/copilot-instructions.md" in paths
    assert "opencode.json" in paths
    assert "kilo.json" in paths

    claude = (repo / "CLAUDE.md").read_text()
    assert "# TestProject" in claude
    assert "agent-sync" in claude


def test_check_detects_missing_files(tmp_path: Path):
    fixture_ai = FIXTURES / ".ai"
    repo = tmp_path / "repo"
    repo.mkdir()
    _copy_tree(fixture_ai, repo / ".ai")

    assert sync(repo, check=True) == 1

    sync(repo, dry_run=False)
    assert sync(repo, check=True) == 0


def _copy_tree(src: Path, dest: Path) -> None:
    import shutil

    shutil.copytree(src, dest)
